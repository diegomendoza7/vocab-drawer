/* Register the service worker generated by the build.
 *
 * Production only, deliberately. In dev the worker would serve a cached bundle
 * over the top of Vite's HMR and every edit would appear not to have happened
 * — a debugging session lost to a caching layer nobody remembered installing.
 *
 * The registration is fire-and-forget: a browser without service workers, or a
 * page served over plain http from something other than localhost, simply does
 * not get offline support. Nothing else in the app depends on it. */
if (import.meta.env.PROD && "serviceWorker" in navigator) {
  window.addEventListener("load", () => {
    navigator.serviceWorker.register("/sw.js").catch((err) => {
      console.warn("[vocab-drawer] offline support unavailable:", err.message);
    });
  });
}

import {LISTEN_VERSION} from './src/data/listening-version.js';
import { writeFileSync, readdirSync, readFileSync } from "node:fs";
import { createHash } from "node:crypto";
import { join, posix } from "node:path";
import { defineConfig } from "vite";
import react from "@vitejs/plugin-react";
import tailwindcss from "@tailwindcss/vite";

const API_PORT = process.env.API_PORT || 8787;

/**
 * Emit a service worker that pre-caches this build.
 *
 * Written by hand rather than pulled from a plugin because the whole app is
 * four runtime dependencies and the caching rules here are three lines of
 * policy — a dependency would be more code to audit than the thing it
 * replaces, and it would decide those rules for us.
 *
 * The rules:
 *   - the built bundle is pre-cached on install, so a cold start with no
 *     network works. It is the whole app: markup, code, vocabulary, icons.
 *   - navigations are network-first, falling back to the cached shell, so a
 *     deploy is picked up when there is a network and the app still opens
 *     when there is not.
 *   - `/api` is never cached. It is word lookup and fact-checking, both of
 *     which are honestly unavailable offline; a stale cached answer would be
 *     worse than the failure message the app already shows.
 */
function offlinePlugin() {
  return {
    name: "vocab-drawer-offline",
    apply: "build",
    closeBundle() {
      const dir = "dist";

      /* Walk the whole build, not just /assets — the word images live under
       * /img and the picture-choice exercise is dead without them offline. */
      const walk = (rel) => readdirSync(join(dir, rel), { withFileTypes: true }).flatMap((e) => {
        const at = rel ? posix.join(rel, e.name) : e.name;
        if (e.isDirectory()) return walk(at);
        if(/(?:transcription-|ort-|french-c1-|german-c1-)/.test(e.name))return [];
        return /\.(js|css|svg|png|webmanifest|ico|woff2)$/.test(e.name) ? [`/${at}`] : [];
      });

      const files = walk("").sort();
      const precache = ["/", "/index.html", ...files];

      /* A real hash of the file list, not a slice of its base64 — the first
       * sixteen characters of that are the same on every build, which would
       * have pinned the cache name forever and never evicted anything. */
      const hash=createHash('sha256');
      for(const path of files)hash.update(path).update(readFileSync(join(dir,path.slice(1))));
      const version = `vd-app-${hash.digest("hex").slice(0, 12)}`;

      writeFileSync(join(dir, "sw.js"), `/* Generated by vite.config.js — do not edit. */
const CACHE = ${JSON.stringify(version)};
const DOWNLOADS = ${JSON.stringify(`vd-downloads-${LISTEN_VERSION}`)};
const PRECACHE = ${JSON.stringify(precache, null, 2)};

self.addEventListener("install", (e) => {
  e.waitUntil(caches.open(CACHE).then((c) => c.addAll(PRECACHE)).then(() => self.skipWaiting()));
});

self.addEventListener("activate", (e) => {
  e.waitUntil(
    caches.keys()
      .then((keys) => Promise.all(keys.filter((k) => k !== CACHE && (k.startsWith("vd-app-") || /^vd-[0-9a-f]{12}$/.test(k) || (k.startsWith("vd-downloads-") && k !== DOWNLOADS))).map((k) => caches.delete(k))))
      .then(() => self.clients.claim()),
  );
});

self.addEventListener("fetch", (e) => {
  const url = new URL(e.request.url);
  if (e.request.method !== "GET" || url.origin !== self.location.origin) return;
  // Lookup and fact-check are honestly unavailable offline; a stale answer
  // would be worse than the failure the app already reports.
  if (url.pathname.startsWith("/api")||url.pathname.startsWith("/models/")) return;

  if (e.request.mode === "navigate") {
    e.respondWith(fetch(e.request).catch(() => caches.match("/index.html")));
    return;
  }
  e.respondWith(
    caches.match(e.request,{ignoreVary:true}).then((hit) => hit || fetch(e.request).then((res) => {
      if (res.ok) { const copy = res.clone(); caches.open(CACHE).then((c) => c.put(e.request, copy)); }
      return res;
    })),
  );
});
`);
      // eslint-disable-next-line no-console
      console.log(`  offline: sw.js precaches ${precache.length} files as ${version}`);
    },
  };
}

export default defineConfig({
  worker:{format:'es'},
  optimizeDeps:{include:['@huggingface/transformers']},
  plugins: [react(), tailwindcss(), offlinePlugin()],
  build: {
    rollupOptions: {
      output: {
        // Keep lazy advanced data separate without pulling shared React code
        // into an advanced chunk that the core app would then need eagerly.
        codeSplitting:{includeDependenciesRecursively:false,groups:[{name(id) {
          if(id.endsWith('/vocab-fr-c1.js'))return 'french-c1';
          if(id.endsWith('/vocab-de-c1.js'))return 'german-c1';
          if (id.includes("node_modules")) return "vendor";
          /* The word-form frequency lists load on demand, the first time a
           * piece of writing is checked — folding them into the eager
           * vocabulary chunk would make every visitor download them. */
          if (id.includes("/src/data/freq/")) return undefined;
          if (id.includes("/src/data/")) return "vocabulary";
          return undefined;
        }}]},
      },
    },
  },
  server: {
    // 5173 is taken by the trade-validator dev server.
    port: 5174,
    strictPort: true,
    // Everything under /api goes to the local proxy, which holds the
    // Anthropic key. Nothing in the browser bundle ever sees it.
    proxy: {
      "/api": {
        target: `http://127.0.0.1:${API_PORT}`,
        changeOrigin: true,
      },
    },
  },
});

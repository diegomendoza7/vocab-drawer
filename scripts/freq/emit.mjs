/* Emit ranks for deck words only, plus the bands the UI reports. */
import { readFileSync, writeFileSync } from "node:fs";
import { DATA } from "../../src/data/vocab.js";

const ranks = JSON.parse(readFileSync("scripts/freq/ranks.json", "utf8"));
const out = { fr: {}, de: {} };
const stats = {};

for (const lang of ["fr", "de"]) {
  let total = 0, found = 0;
  const byLevel = {};
  for (const lv of Object.keys(DATA[lang])) {
    let n = 0, hit = 0;
    for (const d of DATA[lang][lv] || []) {
      for (const w of d.words || []) {
        total += 1; n += 1;
        /* Deck headwords carry articles and elisions the list does not. */
        const key = String(w.t).toLowerCase()
          .replace(/^(le |la |les |l'|un |une |der |die |das )/, "").trim();
        const r = ranks[lang][key];
        if (r) { out[lang][w.t] = r; found += 1; hit += 1; }
      }
    }
    byLevel[lv] = `${hit}/${n}`;
  }
  stats[lang] = { found, total, byLevel };
}

const src = `/* GENERATED by scripts/freq/harvest.mjs + emit.mjs — do not edit by hand.
 *
 * Where each deck word sits in a frequency list built from film subtitles.
 * French from a 5,000-word list, German from 2,000 — so German ranks run out
 * sooner, and a word with no rank is *unranked*, never "rare". The list ended;
 * that is a fact about the list.
 *
 * fr ${stats.fr.found}/${stats.fr.total} · de ${stats.de.found}/${stats.de.total}
 */
export const WORD_RANK = ${JSON.stringify(out)};

/* Nation & Waring's coverage figures are what make a rank worth showing: the
 * first 1,000 word families give about 72% of running text, 2,000 about 80%,
 * 5,000 about 89%. The bands are those thresholds, not round numbers. */
export const FREQ_BANDS = [
  { max: 1000, label: "top 1,000", note: "about 72% of everything written or said" },
  { max: 2000, label: "top 2,000", note: "takes you to about 80% coverage" },
  { max: 5000, label: "top 5,000", note: "takes you to about 89% coverage" },
  { max: Infinity, label: "beyond 5,000", note: "specialised — real, but it buys little coverage" },
];

/* How deep each list goes. It matters: an unranked French word really is
 * outside the top 5,000, while an unranked German word is only outside the top
 * 2,000 — a far weaker claim. Reporting both the same way would overstate what
 * is known about German. */
export const LIST_DEPTH = { fr: 5000, de: 2000 };

export function bandFor(rank) {
  if (!rank) return null;
  return FREQ_BANDS.find((b) => rank <= b.max) || null;
}

/** The band, or an honest statement of what the absence of a rank means. */
export function rankLabel(lang, rank) {
  const band = bandFor(rank);
  if (band) return { label: band.label, note: band.note, ranked: true };
  const depth = LIST_DEPTH[lang] || 2000;
  return {
    label: \`beyond \${depth.toLocaleString()}\`,
    note: \`outside the \${depth.toLocaleString()}-word list this is measured against\`,
    ranked: false,
  };
}
`;
writeFileSync("src/data/frequency.js", src);
console.log("fr:", stats.fr.found + "/" + stats.fr.total, JSON.stringify(stats.fr.byLevel));
console.log("de:", stats.de.found + "/" + stats.de.total, JSON.stringify(stats.de.byLevel));

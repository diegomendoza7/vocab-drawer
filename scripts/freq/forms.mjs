/* Word-form frequency ranks for scoring free writing.
 *
 * `src/data/frequency.js` ranks the deck's headwords — lemmas. A learner's own
 * writing is running text: "allées", "Schwierigkeiten", "gegangen". Ranking
 * that needs a list of *forms*, and it needs one far deeper than the deck.
 *
 * Source: FrequencyWords by Hermit Dave (github.com/hermitdave/FrequencyWords),
 * the 2018 OpenSubtitles lists. Content licensed CC BY-SA 4.0 — the generated
 * files carry the attribution. Subtitles skew towards speech, which is the
 * right bias here: the question is "is this an everyday word", not "does this
 * appear in newspapers".
 *
 * Keeps the top 10,000 forms of each language and drops tokens containing
 * digits. Run by hand — it is a download, not part of `npm run check`:
 *
 *   node scripts/freq/forms.mjs
 */
import { writeFileSync, mkdirSync } from "node:fs";
import { fileURLToPath } from "node:url";

const OUT = fileURLToPath(new URL("../../src/data/freq/", import.meta.url));
const SRC = (l) => `https://raw.githubusercontent.com/hermitdave/FrequencyWords/master/content/2018/${l}/${l}_50k.txt`;
const KEEP = 10000;

mkdirSync(OUT, { recursive: true });

for (const lang of ["fr", "de"]) {
  const res = await fetch(SRC(lang));
  if (!res.ok) throw new Error(`${lang}: HTTP ${res.status}`);
  const words = [];
  const seen = new Set();
  for (const line of (await res.text()).split("\n")) {
    const w = (line.split(" ")[0] || "").trim().toLowerCase().replace(/’/g, "'");
    if (!w || seen.has(w) || /\d/.test(w) || !/^[\p{L}'-]+$/u.test(w)) continue;
    seen.add(w);
    words.push(w);
    if (words.length === KEEP) break;
  }
  writeFileSync(`${OUT}${lang}.js`, `/* Generated by scripts/freq/forms.mjs — do not edit.
 *
 * The ${KEEP.toLocaleString("en")} most frequent ${lang === "fr" ? "French" : "German"} word forms, most frequent first; a
 * form's rank is its line number. From FrequencyWords by Hermit Dave
 * (github.com/hermitdave/FrequencyWords), 2018 OpenSubtitles list,
 * licensed CC BY-SA 4.0. */
export const WORDS = ${JSON.stringify(words.join("\n"))};
`);
  console.log(`${lang}: ${words.length} forms (last: ${words[words.length - 1]})`);
}

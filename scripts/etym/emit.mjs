/* Turn the harvest into the file the app ships.
 *
 * Only what the screen draws survives: the rungs of each chain, and the
 * English cognate where Wiktionary names one. The raw wikitext is dropped —
 * it was useful for checking the parse, but shipping it would triple the
 * payload for a view nobody sees.
 */
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { CODE_TO_LAYER } from "../../src/data/etymology.js";
import { bareForm, buildFamilies, crossLingual } from "../../src/lib/etymology.js";

const raw = JSON.parse(readFileSync("scripts/etym/chains.json", "utf8"));
const entries = Object.values(raw).filter((e) => e.chain && e.chain.length);

const CHAINS = {};
for (const e of entries) {
  const steps = [];
  for (const s of e.chain) {
    const layer = CODE_TO_LAYER[s.lang];
    if (!layer || layer === e.lang) continue;
    if (steps.some((x) => x.l === layer)) continue;
    steps.push({ l: layer, f: bareForm(s.form) });
  }
  if (!steps.length) continue;
  const en = (e.cognates || []).find((c) => c.lang === "en" && c.form);
  CHAINS[`${e.lang}:${e.t}`] = en ? { c: steps, en: en.form } : { c: steps };
}

/* The English limb, where one was found that genuinely merges. Not every
 * family has one: French borrowed `pause` and English borrowed it separately,
 * so there is no shared ancestor to draw and the family keeps two limbs. */
const english = existsSync("scripts/etym/english.json")
  ? JSON.parse(readFileSync("scripts/etym/english.json", "utf8")) : {};

const asSteps = (chain) => {
  const steps = [];
  for (const s of chain) {
    const layer = CODE_TO_LAYER[s.lang];
    if (!layer || layer === "en") continue;
    if (steps.some((x) => x.l === layer)) continue;
    steps.push({ l: layer, f: bareForm(s.form) });
  }
  return steps;
};

const fams = buildFamilies(entries);
const FAMILIES = crossLingual(fams).map((f) => {
  const en = english[`${f.layer}:${f.form}`];
  const out = {
    layer: f.layer, form: f.form,
    members: f.members.map((m) => ({ lang: m.lang, t: m.t, e: m.e, level: m.level })),
  };
  if (en) {
    out.en = en.word;
    CHAINS[`en:${en.word}`] = { c: asSteps(en.chain) };
  }
  return out;
});

const out = `/* GENERATED by scripts/etym/emit.mjs — do not edit by hand.
 *
 * Etymology chains for the core decks, harvested from English Wiktionary and
 * checked by scripts/etym/verify-laws.mjs. Keyed "<lang>:<headword>"; \`c\` is
 * the chain of ancestors newest-first, \`en\` the English cognate Wiktionary
 * names, when it names one.
 *
 * ${Object.keys(CHAINS).length} words, ${FAMILIES.length} families spanning both languages.
 * Harvested ${new Date().toISOString().slice(0, 10)}.
 */
export const CHAINS = ${JSON.stringify(CHAINS)};

/* Roots with a descendant in both decks — the ones that prove the point. */
export const FAMILIES = ${JSON.stringify(FAMILIES, null, 1)};
`;
writeFileSync("src/data/etymology-chains.js", out);
console.log(`emitted ${Object.keys(CHAINS).length} chains, ${FAMILIES.length} cross-language families, ${FAMILIES.filter((f) => f.en).length} with an English limb`);
console.log("with an English cognate:", Object.values(CHAINS).filter((c) => c.en).length);
